using System.Collections.Generic;

namespace Matsuri.Script
{
    /// <summary>サンプル1本ぶん。UI の「サンプルを開く」に並べる。</summary>
    public readonly struct MatsuriSample
    {
        public readonly string Id;
        public readonly string Title;
        public readonly string Description;
        public readonly string Code;

        public MatsuriSample(string id, string title, string description, string code)
        {
            Id = id;
            Title = title;
            Description = description;
            Code = code;
        }
    }

    /// <summary>
    /// 最初から入っているコード (§44) と、お手本のコード (§85)。
    /// 同じ内容が Assets/StreamingAssets/MatsuriSamples/*.matsuri にも置いてある。
    /// </summary>
    public static class MatsuriSamples
    {
        /// <summary>§44「1分目」。起動した瞬間のエディタに入っている、いちばん短いコード。</summary>
        public static string Starter => StarterCode;

        /// <summary>§85 の最終形。ひととおりの機能が入ったお手本。</summary>
        public static string Full => FullCode;

        /// <summary>値段・装飾・時間まで一歩ずつ足していく練習用。</summary>
        public static string Tutorial => TutorialCode;

        /// <summary>チャレンジモード (§47) 用の、条件分岐を使ったコード。</summary>
        public static string Challenge => ChallengeCode;

        /// <summary>花火とイベントだけを楽しむ、見せ場づくりのコード (§22 / §61)。</summary>
        public static string Fireworks => FireworksCode;

        public static IReadOnlyList<MatsuriSample> All => AllSamples;

        public static bool TryGet(string id, out MatsuriSample sample)
        {
            for (int i = 0; i < AllSamples.Count; i++)
            {
                if (string.Equals(AllSamples[i].Id, id, System.StringComparison.OrdinalIgnoreCase))
                {
                    sample = AllSamples[i];
                    return true;
                }
            }
            sample = default;
            return false;
        }

        static readonly List<MatsuriSample> AllSamples = new List<MatsuriSample>
